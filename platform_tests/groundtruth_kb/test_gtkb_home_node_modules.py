def _resolved_note(given: str, real: str) -> str:
    """The resolved folder is named only when it is spelled otherwise than the path as given (letter case aside)."""
    same = os.path.isabs(given) and os.path.normcase(os.path.normpath(given)) == os.path.normcase(real)
    return "" if same else f" (resolved: {real})"


