from __future__ import annotations

import csv
import importlib.util
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
SCRIPT = ROOT / "scripts" / "generate_rule_compatibility_projections.py"


def _load_module():
    spec = importlib.util.spec_from_file_location("test_rule_projection_generator", SCRIPT)
    assert spec and spec.loader
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def _fixture(root: Path, *, missing_canonical: bool = False, count: int = 38) -> Path:
    policy = root / "policy.toml"
    csv_path = root / "moves.csv"
    csv_path.parent.mkdir(parents=True, exist_ok=True)
    with csv_path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow(
            [
                "Current home directory:",
                "Current file name:",
                "New home directory:",
                "New file name:",
            ]
        )
        for index in range(count):
            writer.writerow(
                [
                    f"{root}/.claude/rules",
                    f"rule-{index}.md",
                    f"{root}/config/agent-control",
                    f"gtkb-rule-{index}.md",
                ]
            )
    lines = [
        "schema_version = 1",
        'manifest_path = "moves.csv"',
        "",
        "[retention]",
        f"native_rule_projection_count = {count}",
        "",
    ]
    for index in range(count):
        canonical = root / "config" / "agent-control" / f"gtkb-rule-{index}.md"
        if not missing_canonical or index != 0:
            canonical.parent.mkdir(parents=True, exist_ok=True)
            canonical.write_bytes(f"rule {index}\r\n".encode())
        lines.extend(
            [
                "[[rule_projections]]",
                f'source = ".claude/rules/rule-{index}.md"',
                f'canonical = "config/agent-control/gtkb-rule-{index}.md"',
                'class = "projection"',
                'load_policy = "explicit_query"',
                "",
            ]
        )
    policy.write_text("\n".join(lines), encoding="utf-8")
    return policy


def test_live_policy_count_field_and_retired_writer() -> None:
    module = _load_module()
    policy = module.load_policy(ROOT)
    assert module.native_rule_projection_count(policy) >= 1
    with pytest.raises(module.RuleProjectionError, match="project_harness.py"):
        module.generate(ROOT)


def test_policy_count_is_single_authority(tmp_path: Path) -> None:
    module = _load_module()
    policy_path = _fixture(tmp_path, count=3)
    policy = module.load_policy(tmp_path, policy_path)
    rows = module.projection_rows(policy)
    assert len(rows) == module.native_rule_projection_count(policy) == 3


def test_generate_write_is_retired(tmp_path: Path) -> None:
    module = _load_module()
    policy = _fixture(tmp_path, count=2)
    with pytest.raises(module.RuleProjectionError, match="project_harness.py"):
        module.generate(tmp_path, policy_path=policy)
    assert not (tmp_path / ".claude/rules/rule-0.md").exists()
    completed = subprocess.run(
        [
            sys.executable,
            str(SCRIPT),
            "--project-root",
            str(tmp_path),
            "--policy",
            str(policy),
        ],
        capture_output=True,
        text=True,
        check=False,
    )
    assert completed.returncode == 2
    assert "project_harness.py" in completed.stderr


def test_check_reports_drift_without_writing(tmp_path: Path) -> None:
    module = _load_module()
