def test_explicit_link_rewrite_skips_code_and_preserves_fragment() -> None:
    module = _load_module()
    rewrite = module.LinkRewrite(
        "config/agent-control/gtkb-a.md",
        "gtkb-b.md",
        "config/agent-control/gtkb-b.md",
        1,
    )
    text = "[live](gtkb-b.md#x) ` [inline](gtkb-b.md)`\n```md\n[code](gtkb-b.md)\n```\n"
    rendered = module.stabilize_relative_links(text, "config/agent-control/gtkb-a.md", [rewrite])
    assert "[live](config/agent-control/gtkb-b.md#x)" in rendered
    assert "` [inline](gtkb-b.md)`" in rendered
    assert "[code](gtkb-b.md)" in rendered


def test_unresolved_token_fails_before_write(tmp_path: Path) -> None:
    sys.path.insert(0, str(ROOT / "scripts" / "harness_projection"))
    import project_harness

    plan = project_harness.Plan()
    result = project_harness.substitute(
        "path is {{HARNESS_UNKNOWN_TOKEN}}",
        {"HARNESS_NAME": "x"},
        str(tmp_path / "f.md"),
        plan.gaps,
    )
    assert "{{HARNESS_UNKNOWN_TOKEN}}" in result
    assert plan.gaps and "unresolved token" in plan.gaps[0]
    assert not any(tmp_path.rglob("*"))
